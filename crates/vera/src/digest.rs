//! The identity lane: perceptual digests that say whether two files are the **same picture**.
//!
//! The two perceptual algorithms VER registers (errata E22), in the reference forms E22 names, so
//! a digest from here equals the one any other producer computes from the same pixels:
//! - **PDQ** (`pdq/1.0`): Meta's PDQ as published in ThreatExchange (the C++ reference that the
//!   `pdqhash` / `threatexchange` Python packages wrap): `f32` luma `0..=255` → two rounds of the
//!   Jarosz box filter (rows then columns, window `⌈dimension / 128⌉`) → 64×64 point decimation →
//!   a 16×64 DCT dropping the DC row and column → the 16×16 block against its Torben median, bits
//!   in the reference's hex order. Plus the reference's 0..100 image-domain quality metric.
//! - **pHash** (`phash-dct/64`): `imagehash.phash`: PIL `L` → PIL's Lanczos resize to 32×32
//!   (fixed-point, two passes) → scipy's unnormalised DCT-II on both axes → the 8×8 low-frequency
//!   block including DC against its numpy median → bits row-major, most significant first.
//!
//! [`digest_rgb8`] is bit-exact with both references on 8-bit RGB (`crates/vera/tests/
//! perceptual-vectors.json`: the 21 decoder-corpus Canonical Buffers and the 10 reference-set
//! images, generated by the Python references). [`digest`] takes a `0..=1` luma plane for callers
//! that have one; it scales it for PDQ and quantises it for pHash, so it is the reference algorithm
//! on that luma, not on an RGB picture's reference luma. The algorithms follow the published
//! reference code (Meta's PDQ, BSD; Pillow's resampler, MIT-CMU; imagehash, BSD-2), reproduced
//! arithmetically.
//!
//! Distances are plain Hamming distances; the decision ([`sameness`]) is the studio's: any digest
//! under its tight threshold, or both under loose, is the same picture.

use crate::thresholds;

/// A luma plane, row-major, values in `0.0..=1.0` (anything outside is clamped by the digest).
/// Borrowed, so the caller converts its RGB once and digests twice.
#[derive(Clone, Copy, Debug)]
pub struct Luma<'a> {
    pub width: usize,
    pub height: usize,
    /// `width * height` samples; a shorter slice is an error the digest reports as `None`.
    pub data: &'a [f32],
}

impl<'a> Luma<'a> {
    /// A luma plane over `data` if the dimensions agree with it; `None` otherwise.
    pub fn new(width: usize, height: usize, data: &'a [f32]) -> Option<Luma<'a>> {
        let n = width.checked_mul(height)?;
        (n > 0 && data.len() >= n).then_some(Luma { width, height, data })
    }

    /// The sample at (`x`, `y`), or `0.0` outside the plane (never panics).
    #[inline]
    pub fn at(&self, x: usize, y: usize) -> f32 {
        if x >= self.width || y >= self.height {
            return 0.0;
        }
        y.checked_mul(self.width).and_then(|i| i.checked_add(x)).and_then(|i| self.data.get(i)).copied().unwrap_or(0.0)
    }
}

/// Rec. 601 luma of interleaved `[r, g, b]` rows, the weights the studio used (0.299, 0.587, 0.114),
/// as a plane the digest can read.
pub fn luma_from_rgb(width: usize, height: usize, rgb: &[[f32; 3]]) -> Vec<f32> {
    let n = width.checked_mul(height).unwrap_or(0).min(rgb.len());
    rgb.iter().take(n).map(|[r, g, b]| (0.299 * r + 0.587 * g + 0.114 * b).clamp(0.0, 1.0)).collect()
}

/// Both digests of one frame.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Digest {
    /// PDQ, 256 bits, the reference's byte order.
    pub pdq: [u8; 32],
    /// PDQ's image-domain quality, 0..=100.
    pub pdq_quality: u8,
    /// pHash, 64 bits.
    pub phash: u64,
}

/// What two digests say about two frames.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Sameness {
    /// The same picture: a resize, a re-export, a format change.
    Same,
    /// Possibly the same picture: a variant edit, a heavy crop, a burst neighbour. Worth showing,
    /// never acted on automatically.
    Possible,
    /// Different pictures as far as digests can tell (a crop can still be the same picture: that
    /// is the embedding lane's job).
    Different,
}

/// Both digests of `img`, or `None` when the plane is too small to fingerprint (under 2×2).
///
/// The luma plane is `0..=1`; PDQ reads it scaled to the reference's `0..=255`, pHash reads it
/// quantised to 8 bits (PIL's `L`). For bit-exact reference digests of an 8-bit RGB picture use
/// [`digest_rgb8`], which forms both lumas exactly as the reference implementations do.
pub fn digest(img: &Luma) -> Option<Digest> {
    let (pdq, pdq_quality) = pdq(img)?;
    let phash = phash(img)?;
    Some(Digest { pdq, pdq_quality, phash })
}

/// The two luma planes the reference digests read, built in one pass over an 8-bit RGB picture
/// and shared between PDQ, its quality figure and pHash.
#[derive(Clone, Debug, PartialEq)]
pub struct Planes {
    pub width: usize,
    pub height: usize,
    /// PDQ's luma, `0..=255`: `0.299·R + 0.587·G + 0.114·B` in double precision, stored as `f32`
    /// (what `pdqhash` hands the C++ reference).
    pub luma: Vec<f32>,
    /// PIL's `convert("L")` (ITU-R 601-2 in 16.16 fixed point, rounded): pHash's input.
    pub l8: Vec<u8>,
}

impl Planes {
    /// Both planes of `width × height` interleaved RGB8, or `None` when empty or `rgb` is short.
    pub fn from_rgb8(width: usize, height: usize, rgb: &[u8]) -> Option<Planes> {
        let px = pixels(width, height, rgb)?;
        let n = px.len() / 3;
        let mut luma = Vec::with_capacity(n);
        let mut l8 = Vec::with_capacity(n);
        for p in px.chunks_exact(3) {
            if let [r, g, b] = p {
                luma.push((f64::from(*r) * 0.299 + f64::from(*g) * 0.587 + f64::from(*b) * 0.114) as f32);
                l8.push(((u32::from(*r) * 19595 + u32::from(*g) * 38470 + u32::from(*b) * 7471 + 0x8000) >> 16).min(255) as u8);
            }
        }
        Some(Planes { width, height, luma, l8 })
    }
}

/// Both reference digests of an 8-bit RGB picture (`rgb.len() >= width * height * 3`, row-major,
/// interleaved): bit-exact with Meta's PDQ and `imagehash.phash`. `None` for an empty picture or a
/// short buffer.
pub fn digest_rgb8(width: usize, height: usize, rgb: &[u8]) -> Option<Digest> {
    digest_planes(&Planes::from_rgb8(width, height, rgb)?)
}

/// Both reference digests from prepared [`Planes`].
pub fn digest_planes(p: &Planes) -> Option<Digest> {
    let (pdq, pdq_quality) = pdq_planes(p)?;
    let phash = phash_planes(p)?;
    Some(Digest { pdq, pdq_quality, phash })
}

/// The `width × height` pixels of `rgb`, or `None` when empty or short.
fn pixels(width: usize, height: usize, rgb: &[u8]) -> Option<&[u8]> {
    let n = width.checked_mul(height)?;
    if n == 0 {
        return None;
    }
    rgb.get(..n.checked_mul(3)?)
}

/// PDQ (`pdq/1.0`) of an 8-bit RGB picture and its quality, bit-exact with Meta's reference.
pub fn pdq_rgb8(width: usize, height: usize, rgb: &[u8]) -> Option<([u8; 32], u8)> {
    pdq_planes(&Planes::from_rgb8(width, height, rgb)?)
}

/// PDQ and its quality from prepared [`Planes`].
pub fn pdq_planes(p: &Planes) -> Option<([u8; 32], u8)> {
    let n = p.width.checked_mul(p.height)?;
    Some(pdq_core(p.luma.get(..n)?, p.width, p.height))
}

/// pHash (`phash-dct/64`) of an 8-bit RGB picture, bit-exact with `imagehash.phash`.
pub fn phash_rgb8(width: usize, height: usize, rgb: &[u8]) -> Option<u64> {
    phash_planes(&Planes::from_rgb8(width, height, rgb)?)
}

/// pHash's 32×32 input (PIL's Lanczos resize of the `L` plane), for checking the resample
/// against PIL on its own.
#[doc(hidden)]
pub fn phash_resample(p: &Planes) -> Option<Vec<u8>> {
    pil_resize_l(&p.l8, p.width, p.height, PHASH_GRID, PHASH_GRID)
}

/// pHash from prepared [`Planes`].
pub fn phash_planes(p: &Planes) -> Option<u64> {
    phash_l8(&p.l8, p.width, p.height)
}

/// PDQ's 16×16 DCT block (row-major, before the median) of an 8-bit RGB picture: the
/// reference's `pdqFloat256FromFloatLuma`, for diagnosing a digest against the reference.
#[doc(hidden)]
pub fn pdq_float_rgb8(width: usize, height: usize, rgb: &[u8]) -> Option<Vec<f32>> {
    let p = Planes::from_rgb8(width, height, rgb)?;
    let (_, _, b) = pdq_stages(&p.luma, width, height);
    Some(b.iter().flatten().copied().collect())
}

/// PDQ of `img` and its quality, or `None` for a plane too small to fingerprint (under 2×2) or
/// whose `data` is shorter than `width * height`. The plane is read as luma `0..=1` (clamped, NaN
/// as 0) and scaled to the reference's `0..=255` before [`pdq_core`].
pub fn pdq(img: &Luma) -> Option<([u8; 32], u8)> {
    let plane = sanitised(img)?;
    let scaled: Vec<f32> = plane.into_iter().map(|v| v * 255.0).collect();
    Some(pdq_core(&scaled, img.width, img.height))
}

/// Meta's PDQ (`pdqHash256FromFloatLuma`), step for step in `f32` as the reference computes it:
/// 1. Jarosz filter: two rounds of (a box blur along every row, window `⌈cols / 128⌉`, then one
///    down every column, window `⌈rows / 128⌉`), each a running `f32` sum over the window
///    `[i − ⌊w/2⌋, i + ⌈w/2⌉ − 1]` divided by the samples it covers (fewer at the edges).
/// 2. 64×64 point decimation at row `⌊(i + ½)·rows / 64⌋`, column `⌊(j + ½)·cols / 64⌋`.
/// 3. Quality: `min(100, Σ |⌊(Δ·100)/255⌋| / 90)` over the decimated plane's vertical and
///    horizontal neighbour differences.
/// 4. `B = D·A·Dᵀ` with `D[i][j] = √(2/64)·cos(π/128·(i+1)·(2j+1))` as `f32`, `i < 16`, `j < 64`,
///    accumulated in `f32` in index order.
/// 5. Bit `k = 16·i + j` is `B[i][j] > median` (Torben's: the lower median of the 256). The bits
///    are stored in the reference's hex order: word `k / 16` (printed from word 15 down to word 0),
///    bit `k mod 16` within it, so byte `31 − k / 8` holds bit `k mod 8`.
fn pdq_core(luma: &[f32], w: usize, h: usize) -> ([u8; 32], u8) {
    let (_, quality, b) = pdq_stages(luma, w, h);
    let flat: Vec<f32> = b.iter().flatten().copied().collect();
    let mut sorted = flat.clone();
    sorted.sort_by(f32::total_cmp);
    let median = sorted.get(127).copied().unwrap_or(0.0);
    let mut out = [0u8; 32];
    for (k, v) in flat.iter().enumerate() {
        if *v > median
            && let Some(byte) = out.get_mut(31 - k / 8)
        {
            *byte |= 1 << (k % 8);
        }
    }
    (out, quality)
}

/// The reference's smallest hashable dimension: under it the hash is all zeros, quality 0.
const PDQ_MIN_DIM: usize = 5;

/// Steps 1–4 of [`pdq_core`]: the decimated plane, the quality and the 16×16 block.
fn pdq_stages(luma: &[f32], w: usize, h: usize) -> (Box<[[f32; PDQ_GRID]; PDQ_GRID]>, u8, [[f32; PDQ_BLOCK]; PDQ_BLOCK]) {
    let mut a = Box::new([[0f32; PDQ_GRID]; PDQ_GRID]);
    if w < PDQ_MIN_DIM || h < PDQ_MIN_DIM {
        return (a, 0, [[0f32; PDQ_BLOCK]; PDQ_BLOCK]);
    }
    // A 64×64 input is used as it is (the reference skips the filter for it).
    let filtered;
    let buf1: &[f32] = if w == PDQ_GRID && h == PDQ_GRID {
        luma
    } else {
        let window_rows = jarosz_window(w);
        let window_cols = jarosz_window(h);
        let mut b1 = vec![0f32; luma.len()];
        let mut b2 = vec![0f32; luma.len()];
        box_rows(luma, &mut b2, w, window_rows);
        box_cols(&b2, &mut b1, w, h, window_cols);
        box_rows(&b1, &mut b2, w, window_rows);
        box_cols(&b2, &mut b1, w, h, window_cols);
        filtered = b1;
        &filtered
    };
    // Decimation.
    let cols: Vec<usize> = (0..PDQ_GRID).map(|j| decimation_index(j, w)).collect();
    for (i, row) in a.iter_mut().enumerate() {
        let y = decimation_index(i, h);
        let src = y.checked_mul(w).and_then(|o| buf1.get(o..o.checked_add(w)?)).unwrap_or(&[]);
        for (cell, x) in row.iter_mut().zip(&cols) {
            *cell = src.get(*x).copied().unwrap_or(0.0);
        }
    }
    let quality = pdq_quality(&a);
    let b = dct64_to_16(&a);
    (a, quality, b)
}

/// `computeJaroszFilterWindowSize(old, 64)`: `⌈old / 128⌉` (`(old + 127) / 128`).
fn jarosz_window(old: usize) -> usize {
    old.saturating_add(2 * PDQ_GRID - 1) / (2 * PDQ_GRID)
}

/// The four phase lengths of `box1DFloat` for a vector of `len` and a window of `window`.
fn box_phases(len: usize, window: usize) -> (usize, usize, usize, usize) {
    let window = window.clamp(1, len.max(1));
    let half = (window + 2) / 2;
    (half - 1, window - half + 1, len.saturating_sub(window), half - 1)
}

/// `boxAlongRowsFloat`: `box1DFloat` over every row of `src` into `dst` (both `w` wide). The
/// running sum is `f32` and each output is `sum / count`, the reference's four phases exactly.
/// Rows are processed [`ROW_LANES`] at a time, each with its own running sum (the same operations
/// per row, interleaved), so the dependent adds of one row do not serialise the pass.
fn box_rows(src: &[f32], dst: &mut [f32], w: usize, window: usize) {
    if w == 0 {
        return;
    }
    let (p1, p2, p3, p4) = box_phases(w, window);
    let block = w * ROW_LANES;
    let mut src_blocks = src.chunks_exact(block);
    let mut dst_blocks = dst.chunks_exact_mut(block);
    for (sb, db) in (&mut src_blocks).zip(&mut dst_blocks) {
        box_lanes(sb, db, w, (p1, p2, p3, p4));
    }
    for (row, out) in src_blocks.remainder().chunks_exact(w).zip(dst_blocks.into_remainder().chunks_exact_mut(w)) {
        box_row(row, out, (p1, p2, p3, p4));
    }
}

/// [`ROW_LANES`] rows of `w` in `sb` into `db`: the per-row running sums side by side. Every index
/// is below `w` by the phase arithmetic (`p1 + p2 + p3 = w`, `p3 + p4 ≤ w`), and both blocks are
/// exactly `ROW_LANES · w` long, checked first.
#[allow(clippy::indexing_slicing)]
fn box_lanes(sb: &[f32], db: &mut [f32], w: usize, (p1, p2, p3, p4): (usize, usize, usize, usize)) {
    if sb.len() != ROW_LANES * w || db.len() != ROW_LANES * w || p1 + p2 + p3 != w || p3 + p4 > w {
        return;
    }
    let window = p1 + p2;
    let mut sum = [0f32; ROW_LANES];
    for i in 0..p1 {
        for l in 0..ROW_LANES {
            sum[l] += sb[l * w + i];
        }
    }
    let mut count = p1;
    for i in 0..p2 {
        count += 1;
        let c = count as f32;
        for l in 0..ROW_LANES {
            sum[l] += sb[l * w + p1 + i];
            db[l * w + i] = sum[l] / c;
        }
    }
    let c = count as f32;
    for i in 0..p3 {
        for l in 0..ROW_LANES {
            sum[l] += sb[l * w + window + i];
            sum[l] -= sb[l * w + i];
            db[l * w + p2 + i] = sum[l] / c;
        }
    }
    for i in 0..p4 {
        count = count.saturating_sub(1).max(1);
        let c = count as f32;
        for l in 0..ROW_LANES {
            sum[l] -= sb[l * w + p3 + i];
            db[l * w + p2 + p3 + i] = sum[l] / c;
        }
    }
}

/// Rows processed together by [`box_rows`].
const ROW_LANES: usize = 8;

/// `box1DFloat` over one contiguous row.
fn box_row(row: &[f32], out: &mut [f32], (p1, p2, p3, p4): (usize, usize, usize, usize)) {
    let w = row.len();
    let window = p1 + p2;
    let mut sum = 0f32;
    for v in row.iter().take(p1) {
        sum += v;
    }
    let mut count = p1;
    let (head, rest) = out.split_at_mut(p2.min(w));
    for (o, v) in head.iter_mut().zip(row.iter().skip(p1)) {
        sum += v;
        count += 1;
        *o = sum / count as f32;
    }
    let (mid, tail) = rest.split_at_mut(p3.min(rest.len()));
    for ((o, add), sub) in mid.iter_mut().zip(row.iter().skip(window)).zip(row) {
        sum += add;
        sum -= sub;
        *o = sum / count as f32;
    }
    for (o, sub) in tail.iter_mut().take(p4).zip(row.iter().skip(p3)) {
        sum -= sub;
        count = count.saturating_sub(1).max(1);
        *o = sum / count as f32;
    }
}

/// `boxAlongColsFloat`: `box1DFloat` down every column, computed for all columns at once a row at
/// a time (each column's sequence of `f32` operations is the reference's, only interleaved).
fn box_cols(src: &[f32], dst: &mut [f32], w: usize, h: usize, window: usize) {
    if w == 0 || h == 0 {
        return;
    }
    let (p1, p2, p3, p4) = box_phases(h, window);
    let window = p1 + p2;
    let rows: Vec<&[f32]> = src.chunks_exact(w).collect();
    let mut outs: Vec<&mut [f32]> = dst.chunks_exact_mut(w).collect();
    let mut sum = vec![0f32; w];
    fn add(sum: &mut [f32], r: Option<&&[f32]>) {
        if let Some(r) = r {
            for (s, v) in sum.iter_mut().zip(r.iter()) {
                *s += v;
            }
        }
    }
    fn sub(sum: &mut [f32], r: Option<&&[f32]>) {
        if let Some(r) = r {
            for (s, v) in sum.iter_mut().zip(r.iter()) {
                *s -= v;
            }
        }
    }
    fn emit(sum: &[f32], out: Option<&mut &mut [f32]>, count: usize) {
        if let Some(out) = out {
            let c = count.max(1) as f32;
            for (o, s) in out.iter_mut().zip(sum) {
                *o = s / c;
            }
        }
    }
    for r in 0..p1 {
        add(&mut sum, rows.get(r));
    }
    let mut count = p1;
    for i in 0..p2 {
        add(&mut sum, rows.get(p1 + i));
        count += 1;
        emit(&sum, outs.get_mut(i), count);
    }
    for i in 0..p3 {
        add(&mut sum, rows.get(window + i));
        sub(&mut sum, rows.get(i));
        emit(&sum, outs.get_mut(p2 + i), count);
    }
    for i in 0..p4 {
        sub(&mut sum, rows.get(p3 + i));
        count = count.saturating_sub(1);
        emit(&sum, outs.get_mut(p2 + p3 + i), count);
    }
}

/// PDQ's image-domain quality (`computePDQImageDomainQualityMetric`) of the decimated plane, luma
/// `0..=255`: each neighbour difference truncated to whole hundredths of the range,
/// `min(100, Σ / 90)`.
fn pdq_quality(a: &[[f32; PDQ_GRID]; PDQ_GRID]) -> u8 {
    let step = |u: f32, v: f32| -> i64 {
        let d = (u - v) * 100.0 / 255.0;
        if d.is_finite() { (d as i64).abs() } else { 0 }
    };
    let mut sum: i64 = 0;
    for (upper, lower) in a.iter().zip(a.iter().skip(1)) {
        for (u, v) in upper.iter().zip(lower) {
            sum += step(*u, *v);
        }
    }
    for row in a {
        for pair in row.windows(2) {
            if let [u, v] = pair {
                sum += step(*u, *v);
            }
        }
    }
    u8::try_from((sum / 90).clamp(0, 100)).unwrap_or(100)
}

/// `dct64To16`: `T = D·A` then `B = T·Dᵀ`, `f32` accumulation in index order.
fn dct64_to_16(a: &[[f32; PDQ_GRID]; PDQ_GRID]) -> [[f32; PDQ_BLOCK]; PDQ_BLOCK] {
    // The reference rounds the scale to `f32` first, then multiplies in double precision.
    let scale = f64::from((2.0f64 / PDQ_GRID as f64).sqrt() as f32);
    let mut d = [[0f32; PDQ_GRID]; PDQ_BLOCK];
    for (i, row) in d.iter_mut().enumerate() {
        for (j, v) in row.iter_mut().enumerate() {
            *v = (scale * (std::f64::consts::PI / 2.0 / PDQ_GRID as f64 * (i + 1) as f64 * (2 * j + 1) as f64).cos()) as f32;
        }
    }
    let mut t = [[0f32; PDQ_GRID]; PDQ_BLOCK];
    for (drow, trow) in d.iter().zip(t.iter_mut()) {
        for (j, tv) in trow.iter_mut().enumerate() {
            let mut sum = 0f32;
            for (dk, arow) in drow.iter().zip(a) {
                sum += dk * arow.get(j).copied().unwrap_or(0.0);
            }
            *tv = sum;
        }
    }
    let mut b = [[0f32; PDQ_BLOCK]; PDQ_BLOCK];
    for (trow, brow) in t.iter().zip(b.iter_mut()) {
        for (drow, bv) in d.iter().zip(brow.iter_mut()) {
            let mut sum = 0f32;
            for (tk, dk) in trow.iter().zip(drow) {
                sum += tk * dk;
            }
            *bv = sum;
        }
    }
    b
}

/// pHash of `img`, or `None` for a plane too small to fingerprint (under 2×2) or whose `data` is
/// shorter than `width * height`. The plane (`0..=1`, clamped) is quantised to 8 bits
/// (`round(v·255)`) and hashed as an `L` image by [`phash_l8`].
pub fn phash(img: &Luma) -> Option<u64> {
    let plane = sanitised(img)?;
    let l: Vec<u8> = plane.iter().map(|v| (v * 255.0).round().clamp(0.0, 255.0) as u8).collect();
    phash_l8(&l, img.width, img.height)
}

/// `imagehash.phash` of an 8-bit gray `w × h` picture:
/// 1. PIL `resize((32, 32), LANCZOS)`: the Lanczos-3 kernel stretched by the scale factor,
///    coefficients normalised per output sample then fixed to 22 fractional bits, a horizontal
///    pass rounded to 8 bits and a vertical pass rounded to 8 bits (`ImagingResample`); no pass
///    on an axis that is already 32.
/// 2. `scipy.fftpack.dct` (type II, unnormalised: `2·Σ x·cos(π·k·(2n+1)/64)`) along columns,
///    then rows; the 8×8 low-frequency block **including** DC.
/// 3. Bit `8·u + v` is `C[u][v] > median` (numpy's: the mean of the two middle values), packed
///    row-major with bit 0 the most significant (imagehash's hex string).
fn phash_l8(l: &[u8], w: usize, h: usize) -> Option<u64> {
    let small = pil_resize_l(l, w, h, PHASH_GRID, PHASH_GRID)?;
    // Along axis 0 (columns), then axis 1 (rows), keeping the 8 lowest frequencies of each.
    let mut t = vec![[0f64; PHASH_GRID]; PHASH_BLOCK];
    for x in 0..PHASH_GRID {
        let col: Vec<f64> = small.iter().skip(x).step_by(PHASH_GRID).map(|v| f64::from(*v)).collect();
        for (trow, v) in t.iter_mut().zip(dct2(&col)) {
            if let Some(slot) = trow.get_mut(x) {
                *slot = 2.0 * v;
            }
        }
    }
    let mut c = Vec::with_capacity(PHASH_BLOCK * PHASH_BLOCK);
    for trow in &t {
        c.extend(dct2(trow).into_iter().take(PHASH_BLOCK).map(|v| 2.0 * v));
    }
    let mut sorted = c.clone();
    sorted.sort_by(f64::total_cmp);
    let median = (sorted.get(31).copied()? + sorted.get(32).copied()?) / 2.0;
    let mut out = 0u64;
    for (k, v) in c.iter().enumerate() {
        if *v > median {
            out |= 1u64 << (63 - k);
        }
    }
    Some(out)
}

/// The DCT-II `X[k] = Σ x[n]·cos(π·k·(2n+1)/2N)` of a power-of-two-length `x`, by Lee's
/// recursive even/odd split. Like the FFT scipy computes it with, the split makes structural
/// zeros exact (a constant column has exactly zero AC terms), which a direct cosine sum does not:
/// those zeros decide pHash bits whenever they reach the median.
fn dct2(x: &[f64]) -> Vec<f64> {
    let n = x.len();
    if n <= 1 || !n.is_power_of_two() {
        return x.to_vec();
    }
    let h = n / 2;
    let mut a = Vec::with_capacity(h);
    let mut b = Vec::with_capacity(h);
    for (i, (lo, hi)) in x.iter().zip(x.iter().rev()).take(h).enumerate() {
        a.push(lo + hi);
        b.push((lo - hi) / (2.0 * (std::f64::consts::PI * (2 * i + 1) as f64 / (2 * n) as f64).cos()));
    }
    let (ea, eb) = (dct2(&a), dct2(&b));
    let mut out = Vec::with_capacity(n);
    for k in 0..h {
        out.push(ea.get(k).copied().unwrap_or(0.0));
        out.push(eb.get(k).copied().unwrap_or(0.0) + eb.get(k + 1).copied().unwrap_or(0.0));
    }
    out
}

/// PIL's Lanczos filter: `sinc(x)·sinc(x/3)` on `[−3, 3)`.
fn lanczos(x: f64) -> f64 {
    let sinc = |x: f64| {
        if x == 0.0 {
            1.0
        } else {
            let x = x * std::f64::consts::PI;
            x.sin() / x
        }
    };
    if (-3.0..3.0).contains(&x) { sinc(x) * sinc(x / 3.0) } else { 0.0 }
}

/// PIL's `precompute_coeffs` for `in_size → out_size` over the whole axis, then
/// `normalize_coeffs_8bpc`: per output sample, the first source index and the fixed-point weights.
fn pil_coeffs(in_size: usize, out_size: usize) -> Vec<(usize, Vec<i64>)> {
    let scale = in_size as f32 as f64 / out_size as f64;
    let filterscale = scale.max(1.0);
    let support = 3.0 * filterscale;
    let mut out = Vec::with_capacity(out_size);
    for xx in 0..out_size {
        let center = (xx as f64 + 0.5) * scale;
        let ss = 1.0 / filterscale;
        let xmin = ((center - support + 0.5) as i64).max(0);
        let xmax = ((center + support + 0.5) as i64).min(in_size as i64);
        let n = (xmax - xmin).max(0);
        let mut k: Vec<f64> = (0..n).map(|x| lanczos((x as f64 + xmin as f64 - center + 0.5) * ss)).collect();
        let ww: f64 = k.iter().sum();
        if ww != 0.0 {
            for v in &mut k {
                *v /= ww;
            }
        }
        let fixed =
            k.iter().map(|v| if *v < 0.0 { (-0.5 + v * f64::from(1u32 << 22)) as i64 } else { (0.5 + v * f64::from(1u32 << 22)) as i64 }).collect();
        out.push((usize::try_from(xmin).unwrap_or(0), fixed));
    }
    out
}

/// PIL's `clip8` after a fixed-point accumulation.
fn clip8(ss: i64) -> u8 {
    (ss >> 22).clamp(0, 255) as u8
}

/// PIL's `ImagingResample` of an `L` image with the Lanczos filter, `w × h → ow × oh`: the
/// horizontal pass over the source rows the vertical pass reads, then the vertical pass, each
/// with per-output-sample coefficient tables; no pass on an axis whose size does not change.
fn pil_resize_l(src: &[u8], w: usize, h: usize, ow: usize, oh: usize) -> Option<Vec<u8>> {
    let n = w.checked_mul(h)?;
    if n == 0 {
        return None;
    }
    let src = src.get(..n)?;
    let vert = pil_coeffs(h, oh);
    // Rows the vertical pass reads (PIL's ybox).
    let first = vert.first().map_or(0, |(s, _)| *s);
    let last = vert.last().map_or(h, |(s, k)| s + k.len());
    let horizontal: Option<Vec<u8>> = if w != ow {
        let horiz = pil_coeffs(w, ow);
        let mut tmp = Vec::with_capacity(ow * last.saturating_sub(first));
        for row in src.chunks_exact(w).skip(first).take(last.saturating_sub(first)) {
            for (xmin, k) in &horiz {
                let taps = row.get(*xmin..xmin + k.len())?;
                let ss: i64 = (1 << 21) + taps.iter().zip(k).map(|(p, kv)| i64::from(*p) * kv).sum::<i64>();
                tmp.push(clip8(ss));
            }
        }
        Some(tmp)
    } else {
        None
    };
    let (img, iw, offset): (&[u8], usize, usize) = match &horizontal {
        Some(t) => (t, ow, first),
        None => (src, w, 0),
    };
    if h == oh {
        return (iw == ow).then(|| img.to_vec());
    }
    let mut out = Vec::with_capacity(ow * oh);
    for (ymin, k) in &vert {
        let y0 = ymin.checked_sub(offset)?;
        for x in 0..iw {
            let mut ss: i64 = 1 << 21;
            for (i, kv) in k.iter().enumerate() {
                ss += i64::from(*img.get((y0 + i) * iw + x)?) * kv;
            }
            out.push(clip8(ss));
        }
    }
    (iw == ow).then_some(out)
}

/// PDQ's decimated grid edge and its low-frequency block edge.
const PDQ_GRID: usize = 64;
const PDQ_BLOCK: usize = 16;
/// pHash's resample edge and its low-frequency block edge.
const PHASH_GRID: usize = 32;
const PHASH_BLOCK: usize = 8;

/// `img`'s first `width * height` samples clamped to `0..=1` (NaN as 0), or `None` when the plane
/// is under 2×2 or the slice is short. The allocation is bounded by the caller's slice.
fn sanitised(img: &Luma) -> Option<Vec<f32>> {
    if img.width < 2 || img.height < 2 {
        return None;
    }
    let n = img.width.checked_mul(img.height)?;
    let src = img.data.get(..n)?;
    Some(src.iter().map(|v| if v.is_nan() { 0.0 } else { v.clamp(0.0, 1.0) }).collect())
}

/// `decimateFloat`'s index: `⌊(i + ½)·n / 64⌋` in double precision, kept inside `0..n`.
fn decimation_index(i: usize, n: usize) -> usize {
    ((((i as f64) + 0.5) * n as f64 / PDQ_GRID as f64) as usize).min(n.saturating_sub(1))
}

/// Bits that differ between two PDQ digests.
pub fn hamming256(a: &[u8; 32], b: &[u8; 32]) -> u32 {
    a.iter().zip(b).map(|(x, y)| (x ^ y).count_ones()).sum()
}

/// Bits that differ between two pHash digests.
pub fn hamming64(a: u64, b: u64) -> u32 {
    (a ^ b).count_ones()
}

/// The studio's decision: any digest at or under its tight threshold is the same picture (a PDQ
/// digest only when both frames' quality clears [`thresholds::PDQ_MIN_QUALITY`], a pHash digest
/// only when both clear [`thresholds::PHASH_MIN_QUALITY`]); otherwise both at or under loose is a
/// possible match; otherwise different.
pub fn sameness(a: &Digest, b: &Digest) -> Sameness {
    compare(a, b).sameness
}

/// Distances between two digests, for reports: (PDQ bits of 256, pHash bits of 64).
pub fn distances(a: &Digest, b: &Digest) -> (u32, u32) {
    (hamming256(&a.pdq, &b.pdq), hamming64(a.phash, b.phash))
}

/// The algorithm these digests come from. A store that remembers digests beside this number can
/// tell when a change to the computation (not the thresholds) makes its records stale and must be
/// rebuilt rather than compared with fresh ones. Bumped only when a digest of the same pixels
/// would come out differently.
pub const ALGORITHM_VERSION: u8 = 2;

/// [`sameness`] with the distances it was decided on, computed once.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Comparison {
    pub sameness: Sameness,
    /// PDQ bits of 256 that differ.
    pub pdq: u32,
    /// pHash bits of 64 that differ.
    pub phash: u32,
}

/// Compare two digests: the verdict and both distances in one pass.
pub fn compare(a: &Digest, b: &Digest) -> Comparison {
    let pdq = hamming256(&a.pdq, &b.pdq);
    let phash = hamming64(a.phash, b.phash);
    let pdq_trusted = a.pdq_quality >= thresholds::PDQ_MIN_QUALITY && b.pdq_quality >= thresholds::PDQ_MIN_QUALITY;
    let phash_trusted = a.pdq_quality >= thresholds::PHASH_MIN_QUALITY && b.pdq_quality >= thresholds::PHASH_MIN_QUALITY;
    let sameness = if (pdq_trusted && pdq <= thresholds::PDQ_TIGHT) || (phash_trusted && phash <= thresholds::PHASH_TIGHT) {
        Sameness::Same
    } else if pdq <= thresholds::PDQ_LOOSE && phash <= thresholds::PHASH_LOOSE {
        Sameness::Possible
    } else {
        Sameness::Different
    };
    Comparison { sameness, pdq, phash }
}

